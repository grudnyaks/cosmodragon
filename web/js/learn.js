function numWord(n) {
  if (n === 100) return 'сто';
  if (n < 10) return NUM_UNITS[n];
  if (n < 20) return NUM_TEENS[n - 10];
  const t = Math.floor(n / 10), u = n % 10;
  return NUM_TENS[t] + (u ? ' ' + NUM_UNITS[u] : '');
}
